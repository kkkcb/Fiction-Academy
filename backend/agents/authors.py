def get_author(key: str) -> dict:
    """取作者人格；key 无效直接 KeyError——作者必须显式选择，不存在隐式默认。"""
    return AUTHORS[key]


def resolve_author_for_genre(genre: str) -> str:
    """按书的题材找作者；未匹配返回空串——作者必须显式选择，不再默认凡人流。"""
    for g, author in GENRE_AUTHOR_MAP.items():
        if g in (genre or ""):
            return author
    return ""


def author_for_point(point: str, genre: str = "") -> dict:
    """获取某点位该用哪个作者。题材优先于默认映射。"""
    genre_author = resolve_author_for_genre(genre)
    if point in ("story_core", "character_setting") and genre_author:
        return get_author(genre_author)
    return get_author(POINT_AUTHOR_MAP.get(point, genre_author))
